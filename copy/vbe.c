void vbe_init(multiboot_info_t* mbi) {
    serial_printf("[VBE] Initializing VBE linear framebuffer...\n");
    if (!(mbi->flags & (1 << 12))) {
        serial_printf("[VBE] Error: Framebuffer information not provided by Multiboot!\n");
        return;
    }

    vbe_width = mbi->framebuffer_width;
    vbe_height = mbi->framebuffer_height;
    vbe_pitch = mbi->framebuffer_pitch;
    vbe_bpp = mbi->framebuffer_bpp;
    vbe_phys_fb = (uint32_t)mbi->framebuffer_addr;

    serial_printf("[VBE] Resolving video settings: %dx%d %d-bpp @ 0x%x\n", vbe_width, vbe_height, vbe_bpp, vbe_phys_fb);

    // Map physical framebuffer address space virtually (identity mapping)
    uint32_t fb_size = vbe_width * vbe_height * ((vbe_bpp + 7) / 8);
    for (uint32_t offset = 0; offset < fb_size; offset += 4096) {
        page_map(vbe_phys_fb + offset, vbe_phys_fb + offset, PAGE_PRESENT | PAGE_RW | PAGE_USER);
    }

    // Allocate backbuffer (1024 * 768 * 4 bytes = 3 MB)
    vbe_backbuffer = (uint32_t*)kmalloc(vbe_width * vbe_height * 4);
    if (!vbe_backbuffer) {
        serial_printf("[VBE] Error: Failed to allocate backbuffer!\n");
        // Fallback: draw directly to front buffer
        vbe_backbuffer = (uint32_t*)vbe_phys_fb;
    } else {
        serial_printf("[VBE] Backbuffer allocated at 0x%x\n", vbe_backbuffer);
    }

    vbe_clear(0x121214); // Sleek dark space cadet background color
    vbe_swap_buffers();
}

void vbe_swap_buffers(void) {
    if (!vbe_backbuffer || (uint32_t)vbe_backbuffer == vbe_phys_fb) return;
    
    uint32_t* front = (uint32_t*)vbe_phys_fb;
    uint32_t size_dwords = vbe_width * vbe_height;
    for (uint32_t i = 0; i < size_dwords; i++) {
        front[i] = vbe_backbuffer[i];
    }
}

void vbe_put_pixel(uint32_t x, uint32_t y, uint32_t color) {
    if (!vbe_backbuffer || x >= vbe_width || y >= vbe_height) return;
    vbe_backbuffer[y * vbe_width + x] = color;
}

void vbe_draw_rect(uint32_t x, uint32_t y, uint32_t w, uint32_t h, uint32_t color) {
    for (uint32_t cy = y; cy < y + h; cy++) {
        for (uint32_t cx = x; cx < x + w; cx++) {
            vbe_put_pixel(cx, cy, color);
        }
    }
}

void vbe_draw_char(char c, uint32_t x, uint32_t y, uint32_t fg_color, uint32_t bg_color) {
    if ((uint8_t)c >= 128) return;
    const uint8_t* bitmap = font8x8_basic[(uint8_t)c];
    for (int row = 0; row < 8; row++) {
        for (int col = 0; col < 8; col++) {
            int pixel = bitmap[row] & (1 << col);
            uint32_t color = pixel ? fg_color : bg_color;
            // Draw pixel twice vertically for 8x16 look
            vbe_put_pixel(x + col, y + row * 2, color);
            vbe_put_pixel(x + col, y + row * 2 + 1, color);
        }
    }
}

void vbe_draw_string(const char* str, uint32_t x, uint32_t y, uint32_t fg_color, uint32_t bg_color) {
    uint32_t cx = x;
    while (*str) {
        if (*str == '\n') {
            y += 16;
            cx = x;
        } else {
            vbe_draw_char(*str, cx, y, fg_color, bg_color);
            cx += 8;
        }
        str++;
    }
}

void vbe_clear(uint32_t color) {
    if (!vbe_backbuffer) return;
    uint32_t size_dwords = vbe_width * vbe_height;
    for (uint32_t i = 0; i < size_dwords; i++) {
        vbe_backbuffer[i] = color;
    }
}

void vbe_copy_rect(uint32_t x, uint32_t y, uint32_t w, uint32_t h) {
    if (!vbe_backbuffer || (uint32_t)vbe_backbuffer == vbe_phys_fb) return;
    if (x >= vbe_width || y >= vbe_height) return;
    if (x + w > vbe_width) w = vbe_width - x;
    if (y + h > vbe_height) h = vbe_height - y;
    
    uint32_t* front = (uint32_t*)vbe_phys_fb;
    for (uint32_t cy = y; cy < y + h; cy++) {
        uint32_t offset = cy * vbe_width;
        for (uint32_t cx = x; cx < x + w; cx++) {
            front[offset + cx] = vbe_backbuffer[offset + cx];
        }
    }
}
